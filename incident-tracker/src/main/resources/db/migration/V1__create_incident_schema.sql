-- add a new V<n>__*.sql file instead.

CREATE TABLE incidents (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(200) NOT NULL,
    description      TEXT,
    severity         VARCHAR(16)  NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    source           VARCHAR(16)  NOT NULL,
    rule_id          VARCHAR(64),
    fingerprint      VARCHAR(200),
    affected_user    VARCHAR(100),
    source_ip        VARCHAR(64),
    assignee         VARCHAR(100),
    evidence         TEXT,
    detection_count  INTEGER      NOT NULL DEFAULT 1,
    resolution       TEXT,
    created_by       VARCHAR(100) NOT NULL,
    detected_at      TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    acknowledged_at  TIMESTAMP WITH TIME ZONE,
    resolved_at      TIMESTAMP WITH TIME ZONE,
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_incident_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT chk_incident_status CHECK (status IN ('OPEN', 'INVESTIGATING', 'CONTAINED', 'RESOLVED', 'FALSE_POSITIVE', 'CLOSED')),
    CONSTRAINT chk_incident_source CHECK (source IN ('DETECTION', 'MANUAL'))
);

CREATE INDEX idx_incidents_status      ON incidents (status);
CREATE INDEX idx_incidents_severity    ON incidents (severity);
CREATE INDEX idx_incidents_created_at  ON incidents (created_at);
CREATE INDEX idx_incidents_assignee    ON incidents (assignee);
CREATE INDEX idx_incidents_fingerprint ON incidents (fingerprint);

CREATE TABLE incident_notes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT       NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    author      VARCHAR(100) NOT NULL,
    content     TEXT         NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_notes_incident ON incident_notes (incident_id);

CREATE TABLE incident_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT       NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    action      VARCHAR(32)  NOT NULL,
    from_value  VARCHAR(500),
    to_value    VARCHAR(500),
    actor       VARCHAR(100) NOT NULL,
    timestamp   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_history_incident ON incident_history (incident_id);
